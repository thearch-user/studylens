test('keyboard dialogs, invalid upload and missing narration support', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'speechSynthesis', { value: undefined, configurable: true }); delete (window as unknown as { speechSynthesis?: unknown }).speechSynthesis; });
  await page.goto('/');
  await page.getByRole('button', { name: 'New study set' }).click();
  await expect(page.getByLabel('Study set name')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'New study set' }).click();
  await page.getByLabel('Study set name').fill('Narration fallback');
  await page.getByRole('button', { name: 'Create study set', exact: true }).click();
  await page.getByRole('button', { name: 'Add your first resource' }).click();
  await page.getByLabel('Upload resources').setInputFiles({ name: 'bad.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid') });
  await expect(page.getByText('bad.exe: choose PDF, TXT, or Markdown.')).toBeVisible();
  await page.getByLabel('Upload resources').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Photosynthesis converts sunlight into chemical energy in sugars.') });
  await expect(page.getByText('1 resource ready to study.')).toBeVisible();
  await page.getByRole('button', { name: 'Start studying' }).click();
  await page.getByRole('button', { name: 'Lesson', exact: true }).click();
  await page.getByRole('button', { name: 'Create slide lesson' }).click();
  await expect(page.getByText(/Narration is not supported/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Narrate slide' })).toBeDisabled();
});
